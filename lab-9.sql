CREATE FUNCTION SalesLT.BestRecord
(
	@SDATE Date = '2006-01-01',
	@SNAMELENGTH int = 50,
	@S
)
	RETURNS INT
AS
BEGIN
		DECLARE @BestRecord int
		SELECT TOP 1 @BestRecord = CustomerID
		FROM [240164].Customer
		WHERE ModifiedDate < @SDATE AND CustomerID > 50 AND Title = @STITLE
		ORDER BY FirstName
		RETURN @BestRecord
END

